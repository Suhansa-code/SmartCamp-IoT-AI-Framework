if __name__ == "__main__":
    import sys
    from datetime import timedelta

    logging.basicConfig(level=logging.INFO)
    predictor = LkaResourcePredictor()

    print("\n" + predictor.provenance())

    print("=" * 66)
    print("  DAILY REQUIREMENT — real Sri Lankan event scales")
    print("=" * 66)
    print(f"  {'Scenario':<34}{'People':>8}{'Food kg':>11}{'Water L':>11}")
    for label, pop in [("Median real event (IDMC)", 55),
                       ("Mid-size camp", 500),
                       ("Polonnaruwa, Cyclone Ditwah", 13365)]:
        r = predictor.daily_requirement(
            total_population=pop, children_ratio=0.28,
            elderly_ratio=0.12, pregnant=round(pop * 0.01))
        print(f"  {label:<34}{r['population']:>8,}"
              f"{r['food_kg_day']:>11,.1f}{r['water_liters_day']:>11,.1f}")

    # Seven-day plan on a rising-intake camp
    start = date(2026, 8, 15)
    history = [(start + timedelta(days=i), p)
               for i, p in enumerate([40, 66, 95, 118, 150, 171, 205])]
    plan = predictor.forecast(history=history, children_ratio=0.28,
                              elderly_ratio=0.12, pregnant=3)
    print()
    print(predictor.summary(plan))
