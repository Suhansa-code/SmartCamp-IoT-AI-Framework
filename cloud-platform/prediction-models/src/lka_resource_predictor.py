"""
lka_resource_predictor.py

Sri Lanka camp resource model — food and water only.

Replaces the earlier ResourcePredictor, which was trained on UNHCR/Kaggle
global data. Two things changed:

  1. Scope. Shelter units and medical staffing are out of scope and appear
     nowhere in this module — not as inputs, outputs, or intermediates.

  2. Method. The daily ration is a deterministic rule, not a regressor. The
     old model fitted four regressors to targets that were themselves computed
     as population x constant, so it was learning to re-predict a linear
     function of its own input feature. That produced R2 = 0.9999 and told us
     nothing. The per-person rate is a policy constant, so it is applied as
     one. The statistical component now sits where real uncertainty lives:
     forecasting how the population will move over the next seven days.

Rate provenance lives in models/lka_v2/ration_rates.json, generated by
scripts/build_lka_rate_table.py. Every rate carries an 'evidence' field.

Usage:

    from src.lka_resource_predictor import LkaResourcePredictor

    predictor = LkaResourcePredictor()

    # Today's requirement for a known camp composition
    predictor.daily_requirement(
        total_population = 320,
        children         = 96,
        elderly          = 38,
        pregnant         = 4,
    )

    # Seven-day plan driven by observed registration history
    predictor.forecast(
        history  = [(date(2026, 8, 18), 240), (date(2026, 8, 19), 285), ...],
        children_ratio = 0.28,
        elderly_ratio  = 0.12,
        pregnant       = 4,
    )
"""

import json
import logging
from datetime import date
from pathlib import Path

from population_forecast import forecast_population, DEFAULT_HORIZON

try:
    from lka_intake_model import ChildIntakeModel
except ImportError:  # module is optional; the rate table still works alone
    ChildIntakeModel = None

logger = logging.getLogger(__name__)

_HERE      = Path(__file__).resolve().parent
RATES_PATH = _HERE.parent / "models" / "lka_v2" / "ration_rates.json"


class LkaResourcePredictor:
    """Daily food and drinking-water requirements for a Sri Lankan camp."""

    OUTPUTS = ["food_kg_day", "water_liters_day"]

    def __init__(self, rates_path: Path = RATES_PATH, use_model: bool = True):
        self.rates_path = Path(rates_path)
        self._load()

        # The trained child intake model, when it is available. Children are
        # priced by it whenever individual records are supplied; adults and
        # elderly keep their rate-table values, having no Sri Lankan
        # measurement to train on.
        self.child_model = None
        if use_model and ChildIntakeModel is not None:
            try:
                self.child_model = ChildIntakeModel()
            except FileNotFoundError:
                logger.info("Child intake model not built; using the rate-table constant. "
                            "Run: python scripts/train_lka_intake_model.py")

    def _load(self):
        if not self.rates_path.exists():
            raise FileNotFoundError(
                f"Rate table not found at {self.rates_path}.\n"
                "Run: python scripts/build_lka_rate_table.py"
            )

        self.rates = json.loads(self.rates_path.read_text())

        self.food_child    = float(self.rates["food_child"]["value"])
        self.food_adult    = float(self.rates["food_adult"]["value"])
        # Elderly split at 75 — both bands measured. `food_elderly` is 60-74;
        # the blended value applies when a roster does not distinguish them.
        self.food_elderly         = float(self.rates["food_elderly"]["value"])
        self.food_elderly_75plus  = float(
            self.rates.get("food_elderly_75plus", self.rates["food_elderly"])["value"])
        self.food_elderly_blended = float(
            self.rates.get("food_elderly_blended", self.rates["food_elderly"])["value"])
        self.food_pregnant = float(self.rates["food_pregnant_topup"]["value"])
        self.water_person  = float(self.rates["water_drinking"]["value"])
        self.water_pregnant = float(self.rates["water_pregnant_topup"]["value"])
        self.meals_per_day = int(self.rates["food_adult"].get("meals_per_day", 3))

        logger.info(
            "Rate table v%s loaded: child %.2f / adult %.2f / elderly %.2f kg,"
            " water %.1f L per person per day",
            self.rates.get("schema_version"), self.food_child,
            self.food_adult, self.food_elderly, self.water_person,
        )

    # ------------------------------------------------------------------
    # Public API — daily rule
    # ------------------------------------------------------------------

    def daily_requirement(
        self,
        total_population: int,
        children: int = None,
        elderly: int = None,
        pregnant: int = 0,
        children_ratio: float = None,
        elderly_ratio: float = None,
        children_people: list = None,
        province: str = None,
        elderly_75plus: int = None,
    ) -> dict:
        """
        Food and drinking water for one day, for one camp.

        Give either head counts (children, elderly) or ratios
        (children_ratio, elderly_ratio). Counts win if both are supplied.
        Anyone who is neither a child nor elderly is treated as an adult.

        Returns:
            food_kg_day        — kg of prepared food across three meals
            water_liters_day   — litres of drinking and food-preparation water
            breakdown          — per-cohort contribution, for audit
        """
        pop = max(0, int(total_population))

        if children is None:
            children = int(round(pop * (children_ratio if children_ratio is not None else 0.0)))
        if elderly is None:
            elderly = int(round(pop * (elderly_ratio if elderly_ratio is not None else 0.0)))

        children = max(0, min(int(children), pop))
        elderly  = max(0, min(int(elderly), pop - children))
        adults   = max(0, pop - children - elderly)
        pregnant = max(0, min(int(pregnant), pop))

        # Children are priced by the trained model when their records are
        # given, otherwise by the rate-table constant. Which one was used is
        # reported in the breakdown rather than left implicit.
        child_rate = self.food_child
        child_basis = "rate table constant"
        if children_people and self.child_model is not None:
            predicted = self.child_model.predict_cohort(children_people[:children], province)
            if predicted["children"]:
                child_rate = predicted["mean_kg_per_child"]
                child_basis = f"ML model {self.child_model.artifact['model_id']}"

        food_children = children * child_rate
        food_adults   = adults   * self.food_adult
        # Split the elderly cohort where the roster allows it. Without a split,
        # use the population-weighted blend rather than assuming everyone is in
        # the cheaper band.
        if elderly_75plus is None:
            elderly_older = 0
            elderly_younger = elderly
            elderly_rate_used = self.food_elderly_blended
            food_elderly = elderly * self.food_elderly_blended
        else:
            elderly_older = max(0, min(int(elderly_75plus), elderly))
            elderly_younger = elderly - elderly_older
            food_elderly = (elderly_younger * self.food_elderly
                            + elderly_older * self.food_elderly_75plus)
            elderly_rate_used = (food_elderly / elderly) if elderly else self.food_elderly
        food_topup    = pregnant * self.food_pregnant
        food_total    = food_children + food_adults + food_elderly + food_topup

        water_total = pop * self.water_person + pregnant * self.water_pregnant

        return {
            "population":       pop,
            "food_kg_day":      round(food_total, 1),
            "water_liters_day": round(water_total, 1),
            "meals_per_day":    self.meals_per_day,
            "breakdown": {
                "children":       {"count": children, "rate": round(child_rate, 3),
                                   "food_kg": round(food_children, 1),
                                   "basis": child_basis},
                "adults":         {"count": adults,   "rate": self.food_adult,
                                   "food_kg": round(food_adults, 1)},
                "elderly":        {"count": elderly,
                                   "rate": round(elderly_rate_used, 3),
                                   "food_kg": round(food_elderly, 1),
                                   "aged_60_74": elderly_younger,
                                   "aged_75plus": elderly_older},
                "pregnant_topup": {"count": pregnant, "rate": self.food_pregnant,
                                   "food_kg": round(food_topup, 1)},
                "water_rate_per_person": self.water_person,
            },
            "basis": "deterministic rate table — see models/lka_v2/ration_rates.json",
        }

    # ------------------------------------------------------------------
    # Public API — seven-day plan
    # ------------------------------------------------------------------

    def forecast(
        self,
        history=None,
        horizon_days: int = DEFAULT_HORIZON,
        current_population: int = None,
        children_ratio: float = 0.0,
        elderly_ratio: float = 0.0,
        pregnant: int = 0,
        start_date: date = None,
    ) -> dict:
        """
        Seven-day food and water plan.

        The population path comes from population_forecast.forecast_population;
        the ration rule is then applied to each projected day. Demographic
        ratios are held constant across the horizon — the repository holds no
        evidence that camp composition shifts predictably during an event, so
        projecting a change would be invention.

        Returns:
            daily         — per-day population, food_kg, water_liters, band
            totals        — summed food and water across the horizon
            population    — the underlying forecast object, incl. confidence
        """
        pop_fc = forecast_population(
            history=history or [],
            horizon_days=horizon_days,
            current_population=current_population,
            start_date=start_date,
        )

        # Hold the pregnant count constant; scale cohorts with population.
        daily, food_sum, water_sum = [], 0.0, 0.0
        for day in pop_fc["daily"]:
            req = self.daily_requirement(
                total_population=day["population"],
                children_ratio=children_ratio,
                elderly_ratio=elderly_ratio,
                pregnant=pregnant,
            )
            lo = self.daily_requirement(
                total_population=day["lower"],
                children_ratio=children_ratio,
                elderly_ratio=elderly_ratio, pregnant=pregnant)
            hi = self.daily_requirement(
                total_population=day["upper"],
                children_ratio=children_ratio,
                elderly_ratio=elderly_ratio, pregnant=pregnant)

            food_sum  += req["food_kg_day"]
            water_sum += req["water_liters_day"]

            daily.append({
                "date":             day["date"],
                "day_offset":       day["day_offset"],
                "population":       day["population"],
                "food_kg_day":      req["food_kg_day"],
                "water_liters_day": req["water_liters_day"],
                "food_kg_low":      lo["food_kg_day"],
                "food_kg_high":     hi["food_kg_day"],
            })

        return {
            "horizon_days": horizon_days,
            "daily":        daily,
            "totals": {
                "food_kg":      round(food_sum, 1),
                "water_liters": round(water_sum, 1),
            },
            "population": {
                "method":       pop_fc["method"],
                "confidence":   pop_fc["confidence"],
                "slope_per_day": pop_fc["slope_per_day"],
                "observations": pop_fc["observations"],
                "note":         pop_fc["note"],
            },
        }

    # ------------------------------------------------------------------
    # Presentation
    # ------------------------------------------------------------------

    def summary(self, plan: dict) -> str:
        """Human-readable seven-day plan."""
        pf = plan["population"]
        lines = [
            "=" * 66,
            f"  {plan['horizon_days']}-DAY RESOURCE PLAN"
            f"   (population forecast: {pf['confidence']} confidence)",
            "=" * 66,
            f"  {'Date':<12}{'People':>8}{'Food kg':>11}{'Water L':>11}",
            f"  {'-'*12}{'-'*8:>8}{'-'*11:>11}{'-'*11:>11}",
        ]
        for d in plan["daily"]:
            lines.append(f"  {d['date']:<12}{d['population']:>8,}"
                         f"{d['food_kg_day']:>11,.1f}{d['water_liters_day']:>11,.1f}")
        t = plan["totals"]
        lines += [
            f"  {'-'*42}",
            f"  {'TOTAL':<12}{'':>8}{t['food_kg']:>11,.1f}{t['water_liters']:>11,.1f}",
            "=" * 66,
            f"  Method: {pf['method']}  ({pf['observations']} days observed,"
            f" {pf['slope_per_day']:+.2f} persons/day)",
            f"  {pf['note']}",
            "=" * 66,
        ]
        return "\n".join(lines)

    def provenance(self) -> str:
        """Rate table provenance, for the project report."""
        lines = ["Rate table: " + str(self.rates_path), ""]
        for key in ["food_child", "food_adult", "food_elderly",
                    "food_elderly_75plus", "food_pregnant_topup", "water_drinking"]:
            e = self.rates[key]
            lines.append(f"  {key:<22} {str(e['value']):>6} {e['unit']}")
            lines.append(f"  {'':<22} evidence: {e['evidence']}")
            if e.get("source"):
                lines.append(f"  {'':<22} source:   {e['source']}")
            lines.append("")
        return "\n".join(lines)


